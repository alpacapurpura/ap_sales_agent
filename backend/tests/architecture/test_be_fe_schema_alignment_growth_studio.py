# ─── Tests ────────────────────────────────────────────────────────────────────


class TestSchemaExportExists:
    """Sanity checks on the export artifact itself."""

    def test_all_three_schemas_exported(self, fe_schemas: dict[str, Any]) -> None:
        """Export file must contain all three input schemas."""
        expected = {"StageFilterParams", "ChannelOverviewParams", "TriggerEtlRefreshParams"}
        missing = expected - set(fe_schemas.keys())
        assert not missing, (
            f"FE schema export is missing schemas: {missing}. "
            "Run 'npm run schema:export' in frontend/ and verify the script covers all three schemas."
        )

    def test_fe_schemas_are_objects(self, fe_schemas: dict[str, Any]) -> None:
        """Each exported schema must be a valid JSON Schema object."""
        for name, schema in fe_schemas.items():
            assert isinstance(schema, dict), f"{name}: expected a JSON Schema dict, got {type(schema)}"
            assert "properties" in schema, f"{name}: missing 'properties' key — not a valid object schema"


class TestAdditionalPropertiesForbidden:
    """Both sides must declare extra='forbid' / .strict() to block payload injection."""

    @pytest.mark.parametrize("schema_name", ["StageFilterParams", "ChannelOverviewParams", "TriggerEtlRefreshParams"])
    def test_be_additional_properties_false(self, be_schemas: dict[str, Any], schema_name: str) -> None:
        """BE Pydantic schema must have additionalProperties: false (extra='forbid')."""
        schema = be_schemas[schema_name]
        assert schema.get("additionalProperties") is False, (
            f"BE {schema_name}: expected additionalProperties=false (Pydantic extra='forbid'). "
            "Adversarial defense requires this — removing it allows tenant_id payload smuggling."
        )

    @pytest.mark.parametrize("schema_name", ["StageFilterParams", "ChannelOverviewParams", "TriggerEtlRefreshParams"])
    def test_fe_additional_properties_false(self, fe_schemas: dict[str, Any], schema_name: str) -> None:
        """FE zod schema must have additionalProperties: false (.strict())."""
        schema = fe_schemas[schema_name]
        assert schema.get("additionalProperties") is False, (
            f"FE {schema_name}: expected additionalProperties=false (zod .strict()). "
            "Adversarial defense requires this — mirrors Pydantic extra='forbid'."
        )


class TestFieldNamesAlignment:
    """Every field present in BE must exist in FE and vice-versa."""

    @pytest.mark.parametrize("schema_name", ["StageFilterParams", "ChannelOverviewParams", "TriggerEtlRefreshParams"])
    def test_be_fields_present_in_fe(
        self, be_schemas: dict[str, Any], fe_schemas: dict[str, Any], schema_name: str
    ) -> None:
        """Fields defined in BE Pydantic must all exist in FE zod schema."""
        be_props = set(be_schemas[schema_name].get("properties", {}).keys())
        fe_props = set(fe_schemas[schema_name].get("properties", {}).keys())
        missing_in_fe = be_props - fe_props
        assert not missing_in_fe, (
            f"{schema_name}: BE fields missing from FE zod schema: {missing_in_fe}. "
            "Update frontend/scripts/export-zod-schemas.ts to include all BE fields."
        )

    @pytest.mark.parametrize("schema_name", ["StageFilterParams", "ChannelOverviewParams", "TriggerEtlRefreshParams"])
    def test_fe_fields_present_in_be(
        self, be_schemas: dict[str, Any], fe_schemas: dict[str, Any], schema_name: str
    ) -> None:
        """Fields defined in FE zod must all exist in BE Pydantic schema."""
        be_props = set(be_schemas[schema_name].get("properties", {}).keys())
        fe_props = set(fe_schemas[schema_name].get("properties", {}).keys())
        extra_in_fe = fe_props - be_props
        assert not extra_in_fe, (
            f"{schema_name}: FE zod fields absent from BE Pydantic schema: {extra_in_fe}. "
            "Remove the extra fields from frontend/scripts/export-zod-schemas.ts "
            "or add them to backend/src/modules/copilot/application/tools/_analytics_inputs.py."
        )


class TestEnumValueAlignment:
    """Enum values (stage slugs, channel slugs, period values) must match exactly."""

    @pytest.mark.parametrize(
        "schema_name,field_name",
        [
            ("StageFilterParams", "stage"),
            ("StageFilterParams", "channel"),
            ("StageFilterParams", "period"),
            ("ChannelOverviewParams", "channel"),
            ("TriggerEtlRefreshParams", "channel"),
        ],
    )
    def test_enum_values_match(
        self,
        be_schemas: dict[str, Any],
        fe_schemas: dict[str, Any],
        schema_name: str,
        field_name: str,
    ) -> None:
        """Enum values for a field must be identical between BE and FE."""
        be_prop = be_schemas[schema_name].get("properties", {}).get(field_name)
        fe_prop = fe_schemas[schema_name].get("properties", {}).get(field_name)

        assert be_prop is not None, f"BE {schema_name}.{field_name} not found in schema"
        assert fe_prop is not None, f"FE {schema_name}.{field_name} not found in schema"

        be_enum = _extract_enum_values(be_prop)
        fe_enum = _extract_enum_values(fe_prop)

        assert be_enum is not None, (
            f"BE {schema_name}.{field_name} has no enum values — expected a Literal type; got: {{be_prop}}"
        )
        assert fe_enum is not None, (
            f"FE {schema_name}.{field_name} has no enum values — expected a z.enum() type; got: {{fe_prop}}"
        )

        assert be_enum == fe_enum, (
            f"{schema_name}.{field_name} enum mismatch:\n"
            f"  BE  ({len(be_enum)} values): {be_enum}\n"
            f"  FE  ({len(fe_enum)} values): {fe_enum}\n"
            "Update the out-of-sync side to match. "
            "BE canonical values live in: backend/src/modules/copilot/application/tools/_analytics_inputs.py. "
            "FE canonical values live in: frontend/scripts/export-zod-schemas.ts "
            "(sourced from frontend/src/features/growth-studio/lib/registries/)."
        )


class TestDriftDetection:
    """Meta-test: verify the test itself catches intentional drift.

    This class documents the drift scenarios that would cause failures,
    serving as executable specification for future maintainers.
    """

    def test_stage_enum_count_matches_registry(self, be_schemas: dict[str, Any]) -> None:
        """BE stage enum must have exactly 5 values (one per funnel stage)."""
        stage_prop = be_schemas["StageFilterParams"]["properties"]["stage"]
        stage_enums = _extract_enum_values(stage_prop)
        assert stage_enums is not None
        assert len(stage_enums) == 5, (
            f"Expected exactly 5 stage slugs (one per funnel stage), got {len(stage_enums)}: {stage_enums}. "
            "If a new stage was added, update both BE Literal and FE registry."
        )

    def test_channel_enum_count_matches_registry(self, be_schemas: dict[str, Any]) -> None:
        """BE channel enum must have exactly 5 values (matching CHANNEL_REGISTRY)."""
        channel_prop = be_schemas["ChannelOverviewParams"]["properties"]["channel"]
        channel_enums = _extract_enum_values(channel_prop)
        assert channel_enums is not None
        assert len(channel_enums) == 5, (
            f"Expected exactly 5 channel slugs (matching CHANNEL_REGISTRY), got {len(channel_enums)}: {channel_enums}. "
            "If a new channel was added, update both BE Literal and FE registry."
        )

    def test_period_enum_has_three_values(self, be_schemas: dict[str, Any]) -> None:
        """Period enum must offer exactly 3 time windows: 7d, 30d, 90d."""
        period_prop = be_schemas["StageFilterParams"]["properties"]["period"]
        period_enums = _extract_enum_values(period_prop)
        assert period_enums is not None
        assert sorted(period_enums) == sorted(["7d", "30d", "90d"]), (
            f"Expected period values ['7d', '30d', '90d'], got {period_enums}. "
            "Update BE Literal and FE zod enum if time windows change."
        )

"""Architecture fitness: BE Pydantic ↔ FE zod schema alignment (Story 2B T-5).

Ensures the three analytics copilot tool input schemas stay in sync between
the BE Pydantic models and the FE zod schemas exported via
``npm run schema:export``.

What is checked
---------------
1. ``additionalProperties: false`` present on every exported FE schema
   (mirrors Pydantic ``extra="forbid"``).
2. Every property present in the BE schema also appears in the FE schema
   and vice-versa (no field added on one side without updating the other).
3. Enum values for string-enum fields (``stage``, ``channel``, ``period``)
   match exactly between BE and FE.

Accepted asymmetries (R-4 from 06-tickets.yaml)
------------------------------------------------
- ``required`` list: zod lists fields with ``.default()`` as required; Pydantic
  does not. The test therefore does NOT compare ``required`` lists — only
  field presence and enum values matter for the contract.
- Optional vs nullable: Pydantic marks optional fields as ``anyOf[T, null]``;
  zod marks them optional (absent from ``required``). The test compares enum
  values extracted from the property definition regardless of wrapping shape.

Generation
----------
The FE export is generated by running::

    npm run schema:export

from ``frontend/``. This produces ``frontend/dist/growth-studio-zod-schemas.json``
which this test loads. The test runs the npm script via ``subprocess`` when
the artifact is absent (or stale) so it can run offline in a clean checkout.

Drift detection
---------------
To verify the test catches drift, run::

    python -c "
    import json, pathlib
    p = pathlib.Path('frontend/dist/growth-studio-zod-schemas.json')
    d = json.loads(p.read_text())
    # Simulate drift: remove a stage slug
    d['StageFilterParams']['properties']['stage']['enum'].pop()
    p.write_text(json.dumps(d))
    "
    pytest tests/architecture/test_be_fe_schema_alignment_growth_studio.py -v

Expected output: FAIL with clear diff message pointing to the drifted enum.
"""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from typing import Any

import pytest

# ─── Paths ───────────────────────────────────────────────────────────────────

REPO_ROOT = Path(__file__).resolve().parents[3]  # backend/ → tests/ → architecture/ → ..3 = AISALESHT/
FRONTEND_DIR = REPO_ROOT / "frontend"
FE_EXPORT_FILE = FRONTEND_DIR / "dist" / "growth-studio-zod-schemas.json"
NPM_SCRIPT = "schema:export"


# ─── Helpers ─────────────────────────────────────────────────────────────────


def _run_npm_export() -> None:
    """Run ``npm run schema:export`` in the frontend directory.

    Called when the export artifact is absent so the test is self-healing
    in a clean checkout. Fails the test with a clear message if npm errors.
    """
    result = subprocess.run(  # noqa: S603
        ["npm", "run", NPM_SCRIPT],  # noqa: S607
        cwd=FRONTEND_DIR,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        pytest.fail(
            f"npm run {NPM_SCRIPT} failed (exit {result.returncode}):\nstdout: {result.stdout}\nstderr: {result.stderr}"
        )


def _load_fe_schemas() -> dict[str, Any]:
    """Load the FE zod JSON schema export; regenerate if absent."""
    if not FE_EXPORT_FILE.exists():
        _run_npm_export()
    return json.loads(FE_EXPORT_FILE.read_text())  # type: ignore[return-value]


def _extract_enum_values(prop_schema: dict[str, Any]) -> list[str] | None:
    """Extract enum values from a JSON Schema property, handling anyOf wrapping.

    Pydantic optional fields are ``anyOf[{enum: [...]}, {type: "null"}]``.
    Zod optional fields are plain ``{enum: [...]}`` (not in required list).
    Both representations are normalised to a plain sorted list for comparison.
    """
    # Direct enum field
    if "enum" in prop_schema:
        return sorted(str(v) for v in prop_schema["enum"])

    # Pydantic anyOf nullable pattern: anyOf: [{enum: [...]}, {type: "null"}]
    if "anyOf" in prop_schema:
        for branch in prop_schema["anyOf"]:
            if "enum" in branch:
                return sorted(str(v) for v in branch["enum"])

    return None


